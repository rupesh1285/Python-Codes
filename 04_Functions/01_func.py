# Creating a function

def greet(name):
    return f"Hello, {name}!"

# Calling the function
print(greet("Alice"))  # Output: Hello, Alice!
print(greet("Bob"))    # Output: Hello, Bob!

def add(a, b):
    return a + b

# Calling the function
print(add(5, 3))  # Output: 8
print(add(10, 20))  # Output: 30

