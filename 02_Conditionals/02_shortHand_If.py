# One line if statement

a = 5
b = 2
if a > b: print("a is greater than b")

# One line if else statement

a = 5
b = 2
print("a is greater than b") if a > b else print("a is not greater than b")

# assigning value to variable using If...else statement
x = 10
y = 20
z = x if x > y else y
print(z)  # Output: 20

# Multiple conditions in one line using If...elif...else statement
age = 25
print("You are a child") if age < 13 else print("You are a teenager") if age < 20 else print("You are an adult")

