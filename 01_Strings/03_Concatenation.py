# Concatenation 

# Concatenation Without a Space in Between
a = "Hello"
b = "World"
c = a + b
print(c)


# Concatenation With a Space in Between
e = "Hello"
f = "World"
g = e + " " + f
print(g)

# Concatenation With a Comma in Between
h = "Hello"
i = "World"
j = h + ", " + i
print(j)

# Concatenation With a Plus Sign in Between
k = "Hello"
l = "World" 
m = k + " + " + l
print(m)